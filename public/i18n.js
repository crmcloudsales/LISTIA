  Object.assign(TRANSLATIONS, window.LISTIA_EXTRA_TRANSLATIONS || {});

  function normalizeLanguage(value) {
    const code = String(value || '').trim().toLowerCase().replaceAll('_', '-');
    if (!code) return null;
    return ALIASES[code] || ALIASES[code.split('-')[0]] || null;
  }

  function readCookie() {
    const match = document.cookie.match(/(?:^|;\s*)listia_lang=([^;]+)/);
    return match ? decodeURIComponent(match[1]) : null;
  }

  function detectLanguage() {
    const urlLang = normalizeLanguage(new URLSearchParams(location.search).get('lang'));
    if (urlLang) return urlLang;
    const cookieLang = normalizeLanguage(readCookie());
    if (cookieLang) return cookieLang;
    try {
      const stored = normalizeLanguage(localStorage.getItem(STORAGE_KEY));
      if (stored) return stored;
    } catch {}
    const candidates = navigator.languages?.length ? navigator.languages : [navigator.language || FALLBACK];
    for (const candidate of candidates) {
      const normalized = normalizeLanguage(candidate);
      if (normalized) return normalized;
    }
    return FALLBACK;
  }

  let currentLanguage = detectLanguage();

  function t(key, vars = {}) {
    const table = TRANSLATIONS[currentLanguage] || TRANSLATIONS[FALLBACK];
    let value = table[key] ?? TRANSLATIONS[FALLBACK][key] ?? key;
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{{${name}}}`, String(replacement));
    }
    return value;
  }

  function persistLanguage(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
    if (location.hostname === 'listiaapp.com' || location.hostname.endsWith('.listiaapp.com')) {
      document.cookie = `${COOKIE_KEY}=${encodeURIComponent(lang)}; Path=/; Max-Age=31536000; SameSite=Lax; Domain=.listiaapp.com; Secure`;
    }
  }

  function applyTranslations() {
    const locale = LOCALES[currentLanguage] || LOCALES[FALLBACK];
    document.documentElement.lang = locale.html;
    document.documentElement.dir = locale.direction;
    document.documentElement.dataset.listiaLanguage = currentLanguage;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    const selector = document.getElementById('languageSelect');
    if (selector) {
      selector.value = currentLanguage;
      selector.setAttribute('aria-label', t('language.label'));
      selector.title = t('language.label');
    }

    const manifest = document.getElementById('appManifest');
    if (manifest) manifest.setAttribute('href', `/manifest-${locale.manifest}.webmanifest?v=16`);

    window.dispatchEvent(new CustomEvent('listia:languagechange', {
      detail: { language: currentLanguage, htmlLanguage: locale.html, direction: locale.direction }
    }));
  }

  function setLanguage(lang, { persist = true } = {}) {
    const normalized = normalizeLanguage(lang) || FALLBACK;
    currentLanguage = normalized;
    if (persist) persistLanguage(normalized);
    applyTranslations();
    return normalized;
  }

  window.LISTIA_I18N = {
    t,
    getLanguage: () => currentLanguage,
    setLanguage,
    applyTranslations,
    normalizeLanguage,
    supported: [...SUPPORTED]
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslations, { once: true });
  } else {
    applyTranslations();
  }
